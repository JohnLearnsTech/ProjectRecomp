// Copies app/src/domain into supabase/functions/_shared/domain for the MCP connector, rewritten
// for Deno (explicit .ts extensions, JSON import attributes). The connector then runs exactly
// the code the parity tests cover. Run after changing app/src/domain:
//   node scripts/sync-domain.mjs
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from 'node:fs';
import path from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const src = path.join(root, 'app/src/domain'), dst = path.join(root, 'supabase/functions/_shared/domain');
rmSync(dst, { recursive: true, force: true });
mkdirSync(path.join(dst, 'data'), { recursive: true });
for (const f of readdirSync(src)) {
  if (!f.endsWith('.ts')) continue;
  let s = readFileSync(path.join(src, f), 'utf8');
  s = s.replace(/from '(\.\/[^']+\.json)';/g, "from '$1' with { type: 'json' };");
  s = s.replace(/from '(\.\/[^'.]+)';/g, "from '$1.ts';");
  writeFileSync(path.join(dst, f), '// Generated by scripts/sync-domain.mjs from app/src/domain. Do not edit.\n' + s);
}
for (const f of readdirSync(path.join(src, 'data'))) if (f.endsWith('.json')) copyFileSync(path.join(src, 'data', f), path.join(dst, 'data', f));
console.log('synced', readdirSync(dst).length, 'entries');
